#!/usr/bin/env python3
"""Generate src/vendor_db.h for the Cardputer on-device vendor picker.

Reads the OUI Database cards embedded in src/main.cpp (between the
OUI_DB_START / OUI_DB_END markers, which sync-oui-list.py maintains) and
emits a compact C table. Re-run after sync-oui-list.py.
"""
import html, re, sys

MAIN = "src/main.cpp"
OUT = "src/vendor_db.h"

src = open(MAIN, encoding="utf-8").read()
m = re.search(r"<!-- OUI_DB_START -->(.*?)<!-- OUI_DB_END -->", src, re.S)
if not m:
    sys.exit("[-] OUI_DB markers not found in " + MAIN)

def cstr(s):
    s = html.unescape(s).replace("\u2014", "-").replace("\u2013", "-").replace("\\", "\\\\").replace('"', '\\"')
    return "".join(c if ord(c) < 128 else "?" for c in s)

vendors = []
for block in re.findall(r"<details>(.*?)</details>", m.group(1), re.S):
    name = re.search(r"<summary><b>(.*?)</b>", block, re.S).group(1)
    ouis = [o.replace(":", "") for o in re.findall(r'data-oui="([0-9A-Fa-f:]+)"', block)]
    ble = 'data-ble="true"' in block
    wifi = 'data-wifi="true"' in block
    cat = re.search(r"<strong>Category:</strong>\s*(.*?)</div>", block, re.S)
    if ouis:
        vendors.append((name, cat.group(1).strip() if cat else "", ouis, ble, wifi))

out = ["// GENERATED by gen-cardputer-db.py from the OUI Database in main.cpp.",
       "// Do not edit by hand.", "#pragma once", "",
       "struct CardVendor {", "    const char* name;", "    const char* category;",
       "    const char* ouis;   // concatenated 6-hex-char OUIs", "    uint8_t count;",
       "    bool ble, wifi;", "};", "", "static const CardVendor CARD_VENDORS[] = {"]
for name, cat, ouis, ble, wifi in vendors:
    out.append('    { "%s", "%s", "%s", %d, %s, %s },' % (
        cstr(name), cstr(cat), "".join(o.upper() for o in ouis), len(ouis),
        "true" if ble else "false", "true" if wifi else "false"))
out += ["};", "static const int CARD_VENDOR_COUNT = sizeof(CARD_VENDORS) / sizeof(CARD_VENDORS[0]);", ""]
open(OUT, "w").write("\n".join(out))
print("[+] %d vendors -> %s" % (len(vendors), OUT))
